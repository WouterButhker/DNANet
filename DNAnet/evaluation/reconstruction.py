from typing import Sequence

from DNAnet.data.data_models.hid_image import HIDImage

import numpy as np

from DNAnet.data.data_models.structs import ScanpointPrediction


def reconstruction_mse(
        images: Sequence[HIDImage],
        predictions: Sequence[ScanpointPrediction],
) -> float:
    """
    Computes the mean squared error (MSE) for image reconstructions.

    The function calculates the mean squared error between the true image
    data and the replicated signal generated by predictions. It aggregates
    the MSE for all image-prediction pairs and returns the average MSE
    value over the number of predictions.

    :param images: Sequence of HIDImage objects representing the true images.
    :param predictions: Sequence of Prediction objects representing the predictions.

    :return: The average MSE value across all image-prediction pairs.
    """
    total_mse = 0.0
    if len(predictions) == 0:
        return 0.0
    for image, prediction in zip(images, predictions):
        replicated_signal = prediction.data.squeeze()
        true_signal = image.data.squeeze()
        mse = np.mean((replicated_signal - true_signal) ** 2)
        total_mse += mse
    return total_mse / len(predictions)
